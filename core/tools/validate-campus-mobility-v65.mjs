import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const must=(ok,msg)=>{console.log(`${ok?'PASS':'FAIL'}  ${msg}`);if(!ok)process.exitCode=1};
const mobility=read('lobby/assets/world/campus-mobility-systems.js');
const lite=read('lobby/assets/lobby-lite.js');
const d3=read('lobby/assets/lobby3d.js');
const lobby=read('lobby/assets/lobby.js');
const html=read('lobby/index.html');
const css=read('lobby/assets/lobby.css');
const boot=read('lobby/assets/boot.js');
const sw=read('lobby/sw.js');
const repair=read('repair-lobby.html');
const release=JSON.parse(read('release-current.json'));
for(const token of ['CAMPUS_TRAFFIC_ROUTES','CAMPUS_TRAFFIC_FLEET','CAMPUS_DRIVABLE_VEHICLES','CAMPUS_NPC_PATROLS','CAMPUS_DYNAMIC_SIGNS','CAMPUS_CITY_EVENTS','CAMPUS_INTERIOR_SIGNATURES','CAMPUS_ELEVATOR_SYSTEM','sampleCampusRoute','resolveCampusCityEvent'])must(mobility.includes(token),`módulo mobilidade exporta ${token}`);
must((mobility.match(/routeId:/g)||[]).length>=15,'rotas urbanas alimentam tráfego, veículos e NPCs');
must((mobility.match(/durationMs:/g)||[]).length>=4,'quatro veículos utilizáveis configurados');
must((mobility.match(/role:/g)||[]).length>=5,'NPCs urbanos com papéis contextuais');
must(lite.includes('CAMPUS_TRAFFIC_FLEET')&&lite.includes('useCampusVehicle')&&lite.includes('city-event'),'runtime 2D integra tráfego, direção e eventos');
must(lite.includes('CAMPUS_INTERIOR_SIGNATURES'),'2D diferencia interiores por assinatura funcional');
must(d3.includes('trafficVehicles')&&d3.includes('cityNpcPatrols')&&d3.includes('playerVehicleShell'),'runtime 3D integra tráfego, NPCs e veículo do jogador');
must(d3.includes('elevatorCabin')&&d3.includes('elevatorMotion')&&d3.includes('CAMPUS_ELEVATOR_SYSTEM'),'elevador 3D possui cabine e sequência física');
must(d3.includes('CAMPUS_INTERIOR_SIGNATURES'),'3D diferencia interiores por função');
must(lobby.includes("obj.type==='campus-vehicle'")&&lobby.includes("obj.type==='city-npc'")&&lobby.includes("obj.type==='city-event'"),'controlador integra novas interações urbanas');
must(html.includes('id="vehicle-status"'),'HUD possui estado de veículo ativo');
must(css.includes('.vehicle-status'),'estado de mobilidade possui estilo responsivo');
must(boot.includes('world/campus-mobility-systems.js'),'boot valida módulo de mobilidade');
must(/campus-mobility-systems\.js\?v=14\.10\.8\./.test(sw),'Service Worker cacheia módulo de mobilidade');
must(repair.includes('campus-mobility-systems.js'),'reparo verifica módulo de mobilidade');
const patch=Number(String(release.version||'').split('.').at(-1));must(Number.isFinite(patch)&&patch>=65,'release-current mantém mobilidade v65 ou posterior');
must(![mobility,lite,d3,lobby,html,css,boot,sw].some(t=>/sb_secret|service_role/i.test(t)),'sem segredo Supabase no frontend de mobilidade');
if(process.exitCode)process.exit(process.exitCode);
console.log('\nVALIDAÇÃO Cidade Viva / Mobilidade v65+: PASS');
