import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const must=(ok,msg)=>{console.log(`${ok?'PASS':'FAIL'}  ${msg}`);if(!ok)process.exitCode=1};
const city=read('lobby/assets/world/campus-city-network.js');
const env=read('lobby/assets/world/campus-environment.js');
const lite=read('lobby/assets/lobby-lite.js');
const d3=read('lobby/assets/lobby3d.js');
const boot=read('lobby/assets/boot.js');
const sw=read('lobby/sw.js');
must(city.includes('CAMPUS_ROAD_HIERARCHY'),'rede viária declarada');
must(city.includes('CAMPUS_THEME_PLAZAS'),'praças temáticas declaradas');
must(city.includes('CAMPUS_GARAGES'),'garagens declaradas');
must(city.includes('CAMPUS_PEDESTRIAN_SURFACES'),'passarelas com superfícies físicas');
must(city.includes('CAMPUS_STATION_PROFILES'),'estações com identidade própria');
must(city.includes('CAMPUS_VALE_MONUMENTAL_LINK'),'ligação monumental do Vale declarada');
must(env.includes('createCampusCityLayer'),'render urbano 3D integrado');
must(lite.includes('CAMPUS_ROAD_HIERARCHY')&&lite.includes('CAMPUS_VALE_MONUMENTAL_LINK'),'equivalente urbano 2D integrado');
must(d3.includes('CAMPUS_CITY_LANDMARKS'),'teletransporte 3D inclui cidade');
must(boot.includes('world/campus-city-network.js'),'boot valida módulo urbano');
must(/campus-city-network\.js\?v=14\.10\.8\.\d+/.test(sw),'Service Worker cacheia módulo urbano');
must(![city,env,lite,d3,boot,sw].some(t=>/sb_secret|service_role/i.test(t)),'sem segredo Supabase no frontend urbano');
