import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const must=(ok,msg)=>{console.log(`${ok?'PASS':'FAIL'}  ${msg}`);if(!ok)process.exitCode=1};
const shared=read('lobby/assets/world/vale-silicio-shared.js');
const lobby=read('lobby/assets/lobby.js');
const vale3d=read('lobby/assets/vale3d.js');
const runtime=JSON.parse(read('lobby/data/vale-silicio/runtime-v2.json'));
const spawn=runtime.world?.main_spawn?.position||{};
const companies=(runtime.companies||[]).filter(c=>c.enabled!==false);
const clearance=(c)=>{const p=c.lot?.world_position||{},fp=c.building?.footprint||{};const dx=Math.max(Math.abs(Number(spawn.x||0)-Number(p.x||0))-Number(fp.width||24)/2,0);const dz=Math.max(Math.abs(Number(spawn.z||0)-Number(p.z||0))-Number(fp.depth||20)/2,0);return Math.hypot(dx,dz)};
const nearest=companies.map(c=>({id:c.id,d:clearance(c)})).sort((a,b)=>a.d-b.d)[0];
must(spawn.z===-18,'spawn principal do Vale foi afastado da fachada ao norte');
must(nearest?.d>=15,`spawn mantém área livre de prédios (mínimo ${nearest?.d?.toFixed?.(1)||'—'} m)`);
must(shared.includes("VALE_SPAWN=Object.freeze({x:0,y:.2,z:-18})"),'runtime compartilhado usa o mesmo spawn seguro');
must(shared.includes("id:'praca',name:'Praça Central da Inovação',x:0,z:-18"),'atalho da Praça Central aponta para o spawn seguro');
must(lobby.includes('valeWorldToPresence(VALE_SPAWN.x,VALE_SPAWN.z)'),'entrada do Vale converte o spawn real para presença online');
must(lobby.includes("x:VALE_SPAWN.x,z:VALE_SPAWN.z"),'teleporte/fallback da Praça reutiliza o spawn seguro');
must(vale3d.includes('cameraCollisionRoots')&&!vale3d.includes('getCollisionRoots:()=>[worldRoot]'),'câmera 3D colide só com estruturas sólidas, não com o mundo decorativo inteiro');
must(vale3d.includes('initialYaw:0')&&vale3d.includes('camera.position.set(VALE_SPAWN.x,5.8,VALE_SPAWN.z+13.5)'),'câmera nasce no lado aberto da praça e olhando para o Vale');
must(!vale3d.includes('new THREE.Vector3(0,0,-30)'),'saída de interior não retorna ao spawn antigo');
if(process.exitCode)process.exit(process.exitCode);
console.log('\nVALIDAÇÃO VALE — entrada/câmera v14.10.8.65: PASS');
