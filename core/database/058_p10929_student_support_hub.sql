create table if not exists public.student_support_notifications (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.profiles(id) on delete cascade,
  title text not null check (length(btrim(title)) between 1 and 120),
  body text not null check (length(btrim(body)) between 1 and 1000),
  tone text not null default 'encouragement'
    check (tone in ('encouragement','celebration','guidance','reminder')),
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  read_at timestamptz
);

create index if not exists student_support_notifications_unread_idx
  on public.student_support_notifications(student_id,created_at desc)
  where read_at is null;
create index if not exists student_support_notifications_student_idx
  on public.student_support_notifications(student_id,created_at desc);
create index if not exists student_support_notifications_created_by_idx
  on public.student_support_notifications(created_by)
  where created_by is not null;

alter table public.student_support_notifications enable row level security;
revoke all on table public.student_support_notifications from anon, authenticated;
grant select, update(read_at) on table public.student_support_notifications to authenticated;

drop policy if exists student_support_notifications_select_own on public.student_support_notifications;
create policy student_support_notifications_select_own
  on public.student_support_notifications for select to authenticated
  using (student_id=(select auth.uid()));

drop policy if exists student_support_notifications_mark_own_read on public.student_support_notifications;
create policy student_support_notifications_mark_own_read
  on public.student_support_notifications for update to authenticated
  using (student_id=(select auth.uid()))
  with check (student_id=(select auth.uid()));

